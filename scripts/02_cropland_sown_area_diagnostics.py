"""
Detailed cropland extent--crop sown area diagnostic analysis.

This script is intentionally self-contained and verbose because it is the core
revision step used to separate two quantities that are frequently conflated in
large-scale agricultural land-use studies:

    C_it : physical cropland extent derived from CACD or another annual LULC map
    S_it : official statistical crop sown area, i.e. annual planting activity
    R_it : S_it / C_it, an agricultural-use intensity proxy

The script performs five tasks.

1. Read and harmonize province-by-year tables for cropland extent and crop sown
   area. The expected format is:

       FID | Province | 2000 | 2001 | ... | 2023

   The FID column is optional. Province names are standardized and tables are
   aligned before calculations.

2. Compute relative changes between a base year and an end year:

       gC_i = 100 * (C_i,end - C_i,base) / C_i,base
       gS_i = 100 * (S_i,end - S_i,base) / S_i,base
       DI_i = gS_i - gC_i

   Provinces with |relative change| <= stable threshold are treated as stable.
   The default threshold is ±5%, because stability should not be defined as
   exactly zero change in long-term national datasets.

3. Classify province-level coupling pathways between physical cropland extent
   and annual planting activity:

       C↑–S↑ : joint cropland gain and sown-area increase
       C≈–S↑ : intensified planting under stable cropland extent
       C↓–S↑ : intensified planting under land constraint
       ...

4. Decompose changes in crop sown area using the identity S = C × R:

       ΔS = R0 × ΔC + C0 × ΔR + ΔC × ΔR

   The terms are interpreted as:
       - cropland-extent effect
       - use-intensity effect
       - interaction effect

   This decomposition is exact for each province between base and end year, and
   can also be calculated annually at the national scale.

5. Export transparent tables and publication-ready diagnostic figures. The
   default figures include:
       - coupling typology scatter plot
       - national phase-space trajectory
       - cumulative decomposition of national sown-area change
       - robust temporal envelope for relative changes and use intensity

The script avoids causal language. It identifies diagnostic relationships and
pathways rather than claiming that cropland extent changes cause crop sown-area
changes.
"""

