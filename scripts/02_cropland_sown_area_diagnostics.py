def _axis_limits_with_padding(values: Iterable[float], threshold: float) -> tuple[float, float]:
    finite = np.asarray([v for v in values if np.isfinite(v)], dtype=float)
    if finite.size == 0:
        return -threshold * 1.5, threshold * 1.5
    lo = min(float(np.nanpercentile(finite, 2)), -threshold)
    hi = max(float(np.nanpercentile(finite, 98)), threshold)
    pad = 0.12 * (hi - lo if hi > lo else 1.0)
    return lo - pad, hi + pad


def plot_coupling_scatter(province: pd.DataFrame, output_base: Path, threshold: float, formats: Sequence[str]) -> None:
    fig, ax = plt.subplots(figsize=(7.2, 6.4))
    ax.axhline(0, color=MID_GRAY, lw=0.8, zorder=0)
    ax.axvline(0, color=MID_GRAY, lw=0.8, zorder=0)
    ax.axhspan(-threshold, threshold, color=PALE_GRAY, alpha=0.8, zorder=0)
    ax.axvspan(-threshold, threshold, color=PALE_GRAY, alpha=0.8, zorder=0)
    ax.axhline(threshold, color=MID_GRAY, ls="--", lw=0.8)
    ax.axhline(-threshold, color=MID_GRAY, ls="--", lw=0.8)
    ax.axvline(threshold, color=MID_GRAY, ls="--", lw=0.8)
    ax.axvline(-threshold, color=MID_GRAY, ls="--", lw=0.8)

    for label in COUPLING_ORDER:
        sub = province[province["coupling_type"] == label]
        if sub.empty:
            continue
        ax.scatter(
            sub["gC_percent"],
            sub["gS_percent"],
            s=55,
            color=COUPLING_COLORS[label],
            edgecolor="white",
            linewidth=0.6,
            alpha=0.92,
            label=label,
        )

    ax.set_xlabel("CACD-derived cropland extent change relative to base year (%)")
    ax.set_ylabel("Statistical crop sown-area change relative to base year (%)")
    ax.set_title("Coupling between physical cropland extent and annual planting activity")
    ax.set_xlim(_axis_limits_with_padding(province["gC_percent"], threshold))
    ax.set_ylim(_axis_limits_with_padding(province["gS_percent"], threshold))
    legend_handles = [
        Line2D([0], [0], marker="o", color="none", markerfacecolor=COUPLING_COLORS[k], markeredgecolor="white", label=k)
        for k in COUPLING_ORDER
        if k in set(province["coupling_type"])
    ]
    ax.legend(handles=legend_handles, title="Coupling type", loc="best", frameon=True, ncol=1)
    despine(ax)
    save_figure(fig, output_base, formats)


def plot_phase_space(national: pd.DataFrame, output_base: Path, threshold: float, formats: Sequence[str]) -> None:
    fig, ax = plt.subplots(figsize=(7.2, 6.2))
    ax.axhline(0, color=MID_GRAY, lw=0.8, zorder=0)
    ax.axvline(0, color=MID_GRAY, lw=0.8, zorder=0)
    ax.axhline(threshold, color=MID_GRAY, lw=0.8, ls="--")
    ax.axhline(-threshold, color=MID_GRAY, lw=0.8, ls="--")
    ax.axvline(threshold, color=MID_GRAY, lw=0.8, ls="--")
    ax.axvline(-threshold, color=MID_GRAY, lw=0.8, ls="--")
    ax.axhspan(-threshold, threshold, color=PALE_GRAY, alpha=0.55, zorder=0)
    ax.axvspan(-threshold, threshold, color=PALE_GRAY, alpha=0.35, zorder=0)

    sc = ax.scatter(
        national["gC_percent"],
        national["gS_percent"],
        c=national["year"],
        cmap="viridis",
        s=58,
        edgecolor="white",
        linewidth=0.6,
        zorder=3,
    )
    ax.plot(national["gC_percent"], national["gS_percent"], color=CHARCOAL, lw=1.2, alpha=0.55, zorder=2)

    first = national.iloc[0]
    last = national.iloc[-1]
    ax.text(first.gC_percent, first.gS_percent, str(int(first.year)), fontsize=9, ha="right", va="bottom")
    ax.text(last.gC_percent, last.gS_percent, str(int(last.year)), fontsize=9, ha="left", va="top")

    # Add a small arrow to clarify temporal direction.
    if len(national) > 2:
        p1 = national.iloc[-3]
        p2 = national.iloc[-1]
        ax.annotate(
            "",
            xy=(p2.gC_percent, p2.gS_percent),
            xytext=(p1.gC_percent, p1.gS_percent),
            arrowprops=dict(arrowstyle="->", lw=1.1, color=CHARCOAL),
        )

    cbar = fig.colorbar(sc, ax=ax, pad=0.02)
    cbar.set_label("Year")
    ax.set_xlabel("CACD-derived cropland extent change relative to 2000 (%)")
    ax.set_ylabel("Statistical crop sown-area change relative to 2000 (%)")
    ax.set_title("National phase-space trajectory")
    ax.set_xlim(_axis_limits_with_padding(national["gC_percent"], threshold))
    ax.set_ylim(_axis_limits_with_padding(national["gS_percent"], threshold))
    despine(ax)
    save_figure(fig, output_base, formats)


