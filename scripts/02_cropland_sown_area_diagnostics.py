def relative_change(end_value: pd.Series | np.ndarray, base_value: pd.Series | np.ndarray) -> pd.Series | np.ndarray:
    base = np.asarray(base_value, dtype=float)
    end = np.asarray(end_value, dtype=float)
    with np.errstate(divide="ignore", invalid="ignore"):
        out = 100.0 * (end - base) / base
    return out


def classify_change(value_percent: float, threshold_percent: float) -> str:
    if value_percent > threshold_percent:
        return "increase"
    if value_percent < -threshold_percent:
        return "decrease"
    return "stable"


def direction_symbol(status: str, prefix: str) -> str:
    if status == "increase":
        return f"{prefix}↑"
    if status == "decrease":
        return f"{prefix}↓"
    return f"{prefix}≈"


def coupling_label(g_c: float, g_s: float, threshold_percent: float) -> str:
    c_status = classify_change(g_c, threshold_percent)
    s_status = classify_change(g_s, threshold_percent)
    return f"{direction_symbol(c_status, 'C')}–{direction_symbol(s_status, 'S')}"


def align_tables(cropland: pd.DataFrame, sown: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    common = sorted(set(cropland["Province"]) & set(sown["Province"]))
    missing_c = sorted(set(sown["Province"]) - set(cropland["Province"]))
    missing_s = sorted(set(cropland["Province"]) - set(sown["Province"]))
    if missing_c:
        logging.warning("Provinces present in sown table but absent in cropland table: %s", missing_c)
    if missing_s:
        logging.warning("Provinces present in cropland table but absent in sown table: %s", missing_s)
    if not common:
        raise ValueError("No overlapping province names between cropland and sown-area tables.")
    c = cropland[cropland["Province"].isin(common)].set_index("Province").loc[common].reset_index()
    s = sown[sown["Province"].isin(common)].set_index("Province").loc[common].reset_index()
    return c, s


def build_province_summary(
    cropland: pd.DataFrame,
    sown: pd.DataFrame,
    start_year: int,
    end_year: int,
    threshold_percent: float,
) -> pd.DataFrame:
    c0 = cropland[str(start_year)].astype(float)
    c1 = cropland[str(end_year)].astype(float)
    s0 = sown[str(start_year)].astype(float)
    s1 = sown[str(end_year)].astype(float)

    r0 = s0 / c0
    r1 = s1 / c1
    delta_c = c1 - c0
    delta_s = s1 - s0
    delta_r = r1 - r0

    g_c = relative_change(c1, c0)
    g_s = relative_change(s1, s0)
    di = g_s - g_c

    extent_effect = r0 * delta_c
    intensity_effect = c0 * delta_r
    interaction_effect = delta_c * delta_r
    reconstructed = extent_effect + intensity_effect + interaction_effect

    rows = []
    for i, province in enumerate(cropland["Province"]):
        label = coupling_label(float(g_c[i]), float(g_s[i]), threshold_percent)
        rows.append(
            {
                "Province": province,
                f"C_{start_year}_kha": c0.iloc[i],
                f"C_{end_year}_kha": c1.iloc[i],
                f"S_{start_year}_kha": s0.iloc[i],
                f"S_{end_year}_kha": s1.iloc[i],
                f"R_{start_year}": r0.iloc[i],
                f"R_{end_year}": r1.iloc[i],
                "delta_C_kha": delta_c.iloc[i],
                "delta_S_kha": delta_s.iloc[i],
                "delta_R": delta_r.iloc[i],
                "gC_percent": g_c[i],
                "gS_percent": g_s[i],
                "decoupling_index_pp": di[i],
                "coupling_type": label,
                "coupling_name": COUPLING_NAMES.get(label, label),
                "cropland_extent_effect_kha": extent_effect.iloc[i],
                "use_intensity_effect_kha": intensity_effect.iloc[i],
                "interaction_effect_kha": interaction_effect.iloc[i],
                "reconstructed_delta_S_kha": reconstructed.iloc[i],
                "decomposition_error_kha": delta_s.iloc[i] - reconstructed.iloc[i],
            }
        )
    return pd.DataFrame(rows)


def build_national_timeseries(
    cropland: pd.DataFrame,
    sown: pd.DataFrame,
    start_year: int,
    end_year: int,
) -> pd.DataFrame:
    rows = []
    base_c = cropland[str(start_year)].sum()
    base_s = sown[str(start_year)].sum()
    for year in range(start_year, end_year + 1):
        c = cropland[str(year)].sum()
        s = sown[str(year)].sum()
        r = s / c
        rows.append(
            {
                "year": year,
                "C_kha": c,
                "S_kha": s,
                "R_S_over_C": r,
                "gC_percent": 100.0 * (c - base_c) / base_c,
                "gS_percent": 100.0 * (s - base_s) / base_s,
                "decoupling_index_pp": 100.0 * (s - base_s) / base_s - 100.0 * (c - base_c) / base_c,
            }
        )
    return pd.DataFrame(rows)


def decompose_between(c0: float, s0: float, c1: float, s1: float) -> dict[str, float]:
    r0 = s0 / c0
    r1 = s1 / c1
    delta_c = c1 - c0
    delta_s = s1 - s0
    delta_r = r1 - r0
    extent = r0 * delta_c
    intensity = c0 * delta_r
    interaction = delta_c * delta_r
    return {
        "delta_C_kha": delta_c,
        "delta_S_kha": delta_s,
        "delta_R": delta_r,
        "cropland_extent_effect_kha": extent,
        "use_intensity_effect_kha": intensity,
        "interaction_effect_kha": interaction,
        "reconstructed_delta_S_kha": extent + intensity + interaction,
        "decomposition_error_kha": delta_s - (extent + intensity + interaction),
    }


def build_national_decompositions(
    national: pd.DataFrame,
    start_year: int,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    annual_rows = []
    cumulative_rows = []
    national = national.sort_values("year").reset_index(drop=True)
    for idx in range(1, len(national)):
        prev = national.iloc[idx - 1]
        cur = national.iloc[idx]
        result = decompose_between(prev.C_kha, prev.S_kha, cur.C_kha, cur.S_kha)
        result["year"] = int(cur.year)
        result["from_year"] = int(prev.year)
        result["to_year"] = int(cur.year)
        annual_rows.append(result)

    base = national[national["year"] == start_year].iloc[0]
    for _, cur in national.iterrows():
        result = decompose_between(base.C_kha, base.S_kha, cur.C_kha, cur.S_kha)
        result["year"] = int(cur.year)
        cumulative_rows.append(result)

    return pd.DataFrame(annual_rows), pd.DataFrame(cumulative_rows)


def build_temporal_diagnostics(
    cropland: pd.DataFrame,
    sown: pd.DataFrame,
    start_year: int,
    end_year: int,
    relative_threshold: float = 300.0,
    ratio_threshold: float = 3.0,
) -> pd.DataFrame:
    """Report extreme relative changes and ratios for transparency."""
    rows = []
    c0 = cropland[str(start_year)].astype(float)
    s0 = sown[str(start_year)].astype(float)
    for year in range(start_year, end_year + 1):
        cy = cropland[str(year)].astype(float)
        sy = sown[str(year)].astype(float)
        gy_c = relative_change(cy, c0)
        gy_s = relative_change(sy, s0)
        ratio = sy / cy
        for i, province in enumerate(cropland["Province"]):
            flag = False
            reasons = []
            if abs(gy_c[i]) > relative_threshold:
                flag = True
                reasons.append("extreme_cropland_relative_change")
            if abs(gy_s[i]) > relative_threshold:
                flag = True
                reasons.append("extreme_sown_relative_change")
            if ratio.iloc[i] > ratio_threshold:
                flag = True
                reasons.append("high_sown_to_cropland_ratio")
            rows.append(
                {
                    "Province": province,
                    "year": year,
                    "C_kha": cy.iloc[i],
                    "S_kha": sy.iloc[i],
                    "R_S_over_C": ratio.iloc[i],
                    "gC_percent_from_base": gy_c[i],
                    "gS_percent_from_base": gy_s[i],
                    "flagged": flag,
                    "flag_reason": ";".join(reasons),
                }
            )
    return pd.DataFrame(rows)


