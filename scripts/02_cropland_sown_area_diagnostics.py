def run_diagnostics(
    cropland_file: str | Path,
    sown_file: str | Path,
    output_dir: str | Path,
    start_year: int = 2000,
    end_year: int = 2023,
    stable_threshold_percent: float = 5.0,
    sheet_name: str | int | None = 0,
    input_scale_to_kha: float = 1.0,
    figure_dpi: int = 300,
    save_formats: Sequence[str] = ("png", "pdf"),
) -> DiagnosticOutputs:
    set_publication_style(figure_dpi)
    output_dir = Path(output_dir)
    tables_dir = output_dir / "tables"
    figures_dir = output_dir / "figures"
    tables_dir.mkdir(parents=True, exist_ok=True)
    figures_dir.mkdir(parents=True, exist_ok=True)

    cropland = read_year_table(cropland_file, sheet_name, start_year, end_year, input_scale_to_kha)
    sown = read_year_table(sown_file, sheet_name, start_year, end_year, input_scale_to_kha)
    cropland, sown = align_tables(cropland, sown)

    province = build_province_summary(cropland, sown, start_year, end_year, stable_threshold_percent)
    national = build_national_timeseries(cropland, sown, start_year, end_year)
    annual, cumulative = build_national_decompositions(national, start_year)
    coupling_counts = (
        province.groupby(["coupling_type", "coupling_name"], dropna=False)
        .size()
        .reset_index(name="n_provinces")
        .sort_values("coupling_type")
    )
    temporal = build_temporal_diagnostics(cropland, sown, start_year, end_year)

    write_table(province, tables_dir / "province_summary_coupling_decomposition.csv")
    write_table(national, tables_dir / "national_timeseries_coupling.csv")
    write_table(annual, tables_dir / "national_annual_sown_area_decomposition.csv")
    write_table(cumulative, tables_dir / "national_cumulative_sown_area_decomposition.csv")
    write_table(coupling_counts, tables_dir / "coupling_type_counts.csv")
    write_table(temporal, tables_dir / "temporal_value_diagnostics_all.csv")
    write_table(temporal[temporal["flagged"]], tables_dir / "temporal_value_diagnostics_flagged.csv")

    with pd.ExcelWriter(tables_dir / "integrated_cacd_sown_experiment_results.xlsx") as writer:
        province.to_excel(writer, sheet_name="province_summary", index=False)
        national.to_excel(writer, sheet_name="national_timeseries", index=False)
        annual.to_excel(writer, sheet_name="annual_decomposition", index=False)
        cumulative.to_excel(writer, sheet_name="cumulative_decomposition", index=False)
        coupling_counts.to_excel(writer, sheet_name="coupling_counts", index=False)
        temporal.to_excel(writer, sheet_name="temporal_diagnostics", index=False)

    plot_coupling_scatter(province, figures_dir / "fig2_coupling_typology", stable_threshold_percent, save_formats)
    plot_phase_space(national, figures_dir / "fig3_phase_space", stable_threshold_percent, save_formats)
    plot_cumulative_decomposition(cumulative, figures_dir / "fig3_cumulative_decomposition", save_formats)
    plot_temporal_envelope(temporal, figures_dir / "fig4_temporal_envelope", save_formats)

    note = (
        "Interpretation note:\n"
        "C denotes physical cropland extent derived from CACD. S denotes official statistical crop sown area.\n"
        "R = S/C is used only as an agricultural-use intensity proxy, not as a strict multiple-cropping index.\n"
        "The decomposition Delta S = R0*Delta C + C0*Delta R + Delta C*Delta R is exact.\n"
        "Stable status is defined by the user-specified threshold and is not equivalent to zero change.\n"
    )
    (output_dir / "interpretation_note.txt").write_text(note, encoding="utf-8")

    return DiagnosticOutputs(province, national, annual, cumulative, coupling_counts, temporal)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Detailed cropland extent--crop sown area diagnostic workflow.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--cropland", required=True, help="Province-by-year CACD-derived cropland extent table.")
    parser.add_argument("--sown", required=True, help="Province-by-year official crop sown-area table.")
    parser.add_argument("--output-dir", required=True, help="Directory for all output tables and figures.")
    parser.add_argument("--start-year", type=int, default=2000)
    parser.add_argument("--end-year", type=int, default=2023)
    parser.add_argument("--stable-threshold", type=float, default=5.0, help="Stable threshold in percent.")
    parser.add_argument("--sheet-name", default=0, help="Excel sheet name or index. Ignored for CSV files.")
    parser.add_argument("--input-scale-to-kha", type=float, default=1.0, help="Multiplier used to convert input area values to kha.")
    parser.add_argument("--dpi", type=int, default=300)
    parser.add_argument("--formats", nargs="+", default=["png", "pdf"], help="Figure formats to save.")
    parser.add_argument("--quiet", action="store_true", help="Reduce logging output.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    configure_logging(not args.quiet)
    run_diagnostics(
        cropland_file=args.cropland,
        sown_file=args.sown,
        output_dir=args.output_dir,
        start_year=args.start_year,
        end_year=args.end_year,
        stable_threshold_percent=args.stable_threshold,
        sheet_name=args.sheet_name,
        input_scale_to_kha=args.input_scale_to_kha,
        figure_dpi=args.dpi,
        save_formats=tuple(args.formats),
    )


if __name__ == "__main__":
    main()
