def detect_year_columns(df: pd.DataFrame, start_year: int, end_year: int) -> list[str]:
    expected = {str(y) for y in range(start_year, end_year + 1)}
    year_cols = [c for c in df.columns if str(c).strip() in expected]
    missing = sorted(expected - {str(c).strip() for c in year_cols})
    if missing:
        raise ValueError(f"Missing year columns: {missing[:10]}{'...' if len(missing) > 10 else ''}")
    return [str(y) for y in range(start_year, end_year + 1)]


def normalize_province_name(value: object) -> str:
    text = str(value).strip()
    text = re.sub(r"\s+", " ", text)
    text = text.replace("Province", "").replace("Autonomous Region", "")
    text = text.replace("Municipality", "").strip()
    return text


def read_year_table(
    path: str | Path,
    sheet_name: str | int | None,
    start_year: int,
    end_year: int,
    scale_to_kha: float = 1.0,
    province_column: str = "Province",
) -> pd.DataFrame:
    """Read a province-by-year table and return numeric values in kha."""
    path = Path(path)
    logging.info("Reading year table: %s", path)
    if path.suffix.lower() in {".xlsx", ".xls"}:
        df = pd.read_excel(path, sheet_name=sheet_name)
    else:
        df = pd.read_csv(path)

    if province_column not in df.columns:
        candidates = [c for c in df.columns if str(c).lower() in {"province", "name", "region"}]
        if candidates:
            province_column = candidates[0]
        else:
            raise ValueError(f"Province column {province_column!r} not found in {path}")

    df = df.copy()
    df["Province"] = df[province_column].map(normalize_province_name)
    year_cols = detect_year_columns(df, start_year, end_year)

    out = df[["Province"] + year_cols].copy()
    for col in year_cols:
        out[col] = pd.to_numeric(out[col], errors="coerce") * scale_to_kha
    if out[year_cols].isna().any().any():
        n_missing = int(out[year_cols].isna().sum().sum())
        raise ValueError(f"Table {path} contains {n_missing} missing/non-numeric year values.")
    if out["Province"].duplicated().any():
        duplicates = out.loc[out["Province"].duplicated(), "Province"].tolist()
        raise ValueError(f"Duplicated province names in {path}: {duplicates}")
    return out.sort_values("Province").reset_index(drop=True)


def write_table(df: pd.DataFrame, path: str | Path) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.suffix.lower() in {".xlsx", ".xls"}:
        df.to_excel(path, index=False)
    else:
        df.to_csv(path, index=False, encoding="utf-8-sig")
    logging.info("Saved table: %s", path)


